#!/usr/bin/env node
/**
 * pnpm ui-registry:import-props — per-archetype props seeder.
 *
 * Walks `platform/dos/seed/ui-route/<archetype>/*.json`, validates each
 * payload against ARCHETYPE_PROPS_SCHEMA, and emits ONE forward-only
 * idempotent migration that inserts into the 14 archetype-props tables
 * created by `20260503_0020_phase_f_archetype_props_tables.sql`.
 *
 * Seed-file shape (one file per route):
 *
 *   {
 *     "route": "/admin/foundation/lifecycle",
 *     "archetype": "calendar-timeline",
 *     "calendarEvents": [
 *       { "event_id": "ev-q1-review",
 *         "title_en": "Q1 Maturity Review",
 *         "starts_at": "2026-05-15T09:00:00Z", "category": "internal" }
 *     ]
 *   }
 *
 * Idempotent: every INSERT uses the table's natural unique key
 * (route, <id>) with ON CONFLICT DO UPDATE.
 *
 * Flags:
 *   --dry        Print SQL to stdout, do not write a migration file.
 *   --stamp=…    Override migration filename timestamp (testing).
 *   --tag=…      Suffix label inserted into the filename (default "props").
 *   --root=…     Override seed root (default platform/dos/seed/ui-route).
 */
import { readFileSync, readdirSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ARCHETYPE_PROPS_SCHEMA, buildPropsRows, sqlLiteral } from './lib/props-schema.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const args = new Set(process.argv.slice(2));
const dry = args.has('--dry');
const arg = (name, fallback) => {
  const m = [...args].find(a => a.startsWith(`--${name}=`));
  return m ? m.split('=')[1] : fallback;
};
const stamp = arg('stamp', new Date().toISOString().replace(/[-:T]/g, '').slice(0, 12));
const tag = arg('tag', 'props');
const root = arg('root', join(REPO, 'platform/dos/seed/ui-route'));

if (!existsSync(root)) {
  console.error(`[ui-registry:import-props] seed root not found: ${root}`);
  process.exit(0);
}

function listJson(dir) {
  const out = [];
  for (const e of readdirSync(dir)) {
    const full = join(dir, e);
    const st = statSync(full);
    if (st.isDirectory()) out.push(...listJson(full));
    else if (e.endsWith('.json')) out.push(full);
  }
  return out;
}

const files = listJson(root);
if (!files.length) {
  console.log('[ui-registry:import-props] no seed files — nothing to write.');
  process.exit(0);
}

const inserts = new Map(); // table -> { cols, rows: [obj] }
const skipped = [];
const errors = [];

for (const f of files) {
  let payload;
  try {
    payload = JSON.parse(readFileSync(f, 'utf8'));
  } catch (e) {
    errors.push(`${f}: parse error ${e.message}`);
    continue;
  }
  const route = payload.route;
  const archetype = payload.archetype;
  if (!route || !archetype) {
    skipped.push(`${f}: missing route|archetype`);
    continue;
  }
  let built;
  try {
    built = buildPropsRows(archetype, route, payload);
  } catch (e) {
    errors.push(`${f}: ${e.message}`);
    continue;
  }
  for (const { schema, row } of built) {
    let bucket = inserts.get(schema.table);
    if (!bucket) {
      bucket = { cols: schema.cols, rows: [], naturalKey: schema.cols[0] === 'route' ? schema.cols.slice(0, 2) : schema.cols.slice(0, 1) };
      inserts.set(schema.table, bucket);
    }
    bucket.rows.push(row);
  }
}

if (errors.length) {
  for (const e of errors) console.error(`  ✗ ${e}`);
  console.error(`[ui-registry:import-props] ${errors.length} validation errors — aborting.`);
  process.exit(1);
}

const totalRows = [...inserts.values()].reduce((n, b) => n + b.rows.length, 0);
const naturalKeys = {
  'dos.ui_route_calendar_event':              ['route','event_id'],
  'dos.ui_route_roadmap_milestone':           ['route','milestone_id'],
  'dos.ui_route_org_chart_node':              ['route','node_id'],
  'dos.ui_route_ownership_edge':              ['route','edge_id'],
  'dos.ui_route_delegation_rule':             ['route','rule_id'],
  'dos.ui_route_agent_registry':              ['route','agent_id'],
  'dos.ui_route_agent_flow_step':             ['route','step_id'],
  'dos.ui_route_incident_runbook_step':       ['route','step_id'],
  'dos.ui_route_incident_communication':      ['route','comm_id'],
  'dos.ui_route_audit_ledger_row':            ['route','ledger_id'],
  'dos.ui_route_audit_evidence_artifact':     ['route','artifact_id'],
  'dos.ui_route_follow_up_item':              ['route','item_id'],
  'dos.ui_route_export_artifact':             ['route','artifact_id'],
  'dos.ui_route_workflow_timeline_step':      ['route','step_id'],
  'dos.ui_route_case_finalization':           ['route','case_id'],
};

const header = [
  '-- Auto-generated by `pnpm ui-registry:import-props`. Do not edit by hand.',
  '-- Idempotent: each INSERT uses ON CONFLICT (natural-key) DO UPDATE.',
  `-- Files scanned : ${files.length}`,
  `-- Tables touched: ${inserts.size}`,
  `-- Rows emitted  : ${totalRows}`,
  ...skipped.map(s => `--   ⚠ ${s}`),
].join('\n');

const blocks = [];
for (const [table, { cols, rows }] of inserts) {
  if (!rows.length) continue;
  const nk = naturalKeys[table] ?? ['route'];
  const updateCols = cols.filter(c => !nk.includes(c));
  const values = rows.map(r => `  (${cols.map(c => sqlLiteral(r[c])).join(', ')})`).join(',\n');
  blocks.push(
    `INSERT INTO ${table} (${cols.join(', ')}) VALUES\n${values}\nON CONFLICT (${nk.join(', ')}) DO UPDATE SET\n  ${updateCols.map(c => `${c}=EXCLUDED.${c}`).join(',\n  ')};`
  );
}

const sql = `${header}\n\nBEGIN;\n\n${blocks.join('\n\n')}\n\nCOMMIT;\n`;

if (dry) {
  process.stdout.write(sql);
  console.error(`[ui-registry:import-props] dry — files=${files.length} tables=${inserts.size} rows=${totalRows}`);
  process.exit(0);
}

const MIG_DIR = join(REPO, 'platform/dos/migrations/public');
const file = join(MIG_DIR, `${stamp}_phase_f_${tag}.sql`);
writeFileSync(file, sql, 'utf8');
console.log(`[ui-registry:import-props] wrote ${file}`);
console.log(`  files=${files.length} tables=${inserts.size} rows=${totalRows} skipped=${skipped.length}`);
