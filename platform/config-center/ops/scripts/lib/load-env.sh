#!/usr/bin/env bash

dos_load_env_file() {
  local env_file="${1:-}"
  local line trimmed key value

  if [[ -z "$env_file" || ! -f "$env_file" ]]; then
    return 1
  fi

  while IFS= read -r line || [[ -n "$line" ]]; do
    line=${line%$'\r'}
    trimmed="${line#"${line%%[![:space:]]*}"}"

    [[ -z "$trimmed" || ${trimmed:0:1} == '#' ]] && continue

    if [[ $trimmed == export[[:space:]]* ]]; then
      trimmed="${trimmed#export }"
      trimmed="${trimmed#"${trimmed%%[![:space:]]*}"}"
    fi

    [[ $trimmed != *=* ]] && continue

    key="${trimmed%%=*}"
    value="${trimmed#*=}"
    key="${key%"${key##*[![:space:]]}"}"

    if [[ ! $key =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]]; then
      continue
    fi

    printf -v "$key" '%s' "$value"
    export "$key"
  done < "$env_file"

  return 0
}

dos_load_shared_env() {
  local script_dir repo_root shared_env local_docker_env

  script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  repo_root="$(cd "$script_dir/../../.." && pwd)"
  shared_env="$repo_root/platform/config-center/env/.env.shared"
  local_docker_env="$repo_root/platform/config-center/env/.env.local.docker"

  dos_load_env_file "$shared_env"

  # Optional: local Docker data-plane (Postgres/Redis) generated by ops/scripts/bring-up-stack.sh --with-docker-db.
  # Loaded after .env.shared so DATABASE_URL / REDIS_URL can override for dev machines.
  if [[ -f "$local_docker_env" ]]; then
    dos_load_env_file "$local_docker_env" || true
  fi

  return 0
}