#!/usr/bin/env tsx
/**
 * DKNF fix planner.
 *
 * Targets the one DKNF violation the grader auto-detects:
 *   CHECK (col IN ('a','b','c')) on a TEXT/VARCHAR column
 *
 * Proposes a CREATE TYPE ... AS ENUM + ALTER TABLE ALTER COLUMN TYPE
 * migration template, commented-out. The operator reviews per-column
 * because changing a column type under an existing CHECK + default
 * requires care with existing rows.
 *
 * Emits:
 *   ops/normalization/proposals/dknf/decisions.md
 *   ops/normalization/proposals/dknf/<table>.sql  (commented scaffold)
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { join } from 'path';

const REPO_ROOT = process.cwd();
const SCORECARD = join(REPO_ROOT, 'ops/normalization/normalization-scorecard.json');
const CATALOG = join(REPO_ROOT, 'ops/normalization/catalog.yml');
const OUT_DIR = join(REPO_ROOT, 'ops/normalization/proposals/dknf');

if (!existsSync(SCORECARD)) { console.error('scorecard missing — run normalize-grade.ts first'); process.exit(2); }
if (!existsSync(CATALOG)) { console.error('catalog.yml missing'); process.exit(2); }

const data = JSON.parse(readFileSync(SCORECARD, 'utf-8')) as { scores: Array<{ table: string; layer: string; checks: Record<string, { verdict: string; details: string[] }> }> };

// Parse CHECK expressions from catalog.yml so we can emit real ENUM values per column.
interface CheckInfo { table: string; column: string; values: string[] }
function parseChecks(): CheckInfo[] {
  const text = readFileSync(CATALOG, 'utf-8');
  const out: CheckInfo[] = [];
  let cur = '';
  let mode: 'constraints' | null = null;
  for (const line of text.split('\n')) {
    const nm = line.match(/^  - name:\s*(.+)$/);
    if (nm) { cur = nm[1].trim(); mode = null; continue; }
    if (line === '    constraints:') { mode = 'constraints'; continue; }
    if (line.startsWith('    smells:') || line.startsWith('    monolith_ref:') || line.startsWith('    columns:') || line.startsWith('    sources:') || line.startsWith('    create_sources:') || line.startsWith('    alter_sites:') || line.startsWith('    schemas:')) { mode = null; continue; }
    if (mode === 'constraints') {
      const km = line.match(/^      - \{ kind:\s*CHECK,\s*columns:\s*\[([^\]]*)\].*expression:\s*"([^"]+)"/);
      if (km) {
        const col = km[1].split(',')[0].trim();
        const exprM = km[2].match(/(\w+)\s+IN\s*\(([^)]+)\)/i);
        if (exprM) {
          const values = exprM[2].split(',').map((v) => v.trim().replace(/^'|'$/g, ''));
          out.push({ table: cur, column: exprM[1] || col, values });
        }
      }
    }
  }
  return out;
}

const checks = parseChecks();
const checksByTable = new Map<string, CheckInfo[]>();
for (const c of checks) {
  if (!checksByTable.has(c.table)) checksByTable.set(c.table, []);
  checksByTable.get(c.table)!.push(c);
}

mkdirSync(OUT_DIR, { recursive: true });

interface Row { table: string; layer: string; column: string; enumName: string; values: string[] }
const rows: Row[] = [];

for (const s of data.scores) {
  if (s.checks['DKNF'].verdict !== 'fail') continue;
  const ccs = checksByTable.get(s.table) ?? [];
  for (const d of s.checks['DKNF'].details) {
    const m = d.match(/^check-in-list-on-text:([^:]+):(\d+)-values$/);
    if (!m) continue;
    const col = m[1];
    const ci = ccs.find((c) => c.column === col);
    if (!ci) continue;
    rows.push({
      table: s.table, layer: s.layer, column: col,
      enumName: `${s.table}_${col}_enum`.slice(0, 63).toLowerCase(),
      values: ci.values,
    });
  }
}

// Per-table SQL scaffold
const byTable = new Map<string, Row[]>();
for (const r of rows) {
  if (!byTable.has(r.table)) byTable.set(r.table, []);
  byTable.get(r.table)!.push(r);
}

for (const [table, ts] of byTable) {
  const layer = ts[0].layer;
  const q = layer === 'tenant' ? '__TENANT_SCHEMA__' : 'public';
  const lines: string[] = [];
  lines.push(`-- DKNF ENUM promotions for ${table}`);
  lines.push(`-- Generated by dknf-fix-plan.ts. All statements commented out.`);
  lines.push(`-- Per column: create a dedicated ENUM type, then ALTER the column`);
  lines.push(`-- TYPE to use it (implicit cast via USING), then drop the CHECK constraint.`);
  lines.push('');
  for (const r of ts) {
    const vals = r.values.map((v) => `'${v.replace(/'/g, "''")}'`).join(', ');
    lines.push(`-- ─── ${r.table}.${r.column} (${r.values.length} values) ───`);
    lines.push(`-- CREATE TYPE ${q}.${r.enumName} AS ENUM (${vals});`);
    lines.push(`-- ALTER TABLE ${q}.${r.table}`);
    lines.push(`--   ALTER COLUMN ${r.column} TYPE ${q}.${r.enumName}`);
    lines.push(`--   USING ${r.column}::${q}.${r.enumName};`);
    lines.push(`-- -- drop the now-redundant CHECK constraint; name is Postgres-auto unless you renamed it:`);
    lines.push(`-- -- SELECT conname FROM pg_constraint WHERE conrelid = '${q}.${r.table}'::regclass AND contype='c';`);
    lines.push('');
  }
  writeFileSync(join(OUT_DIR, `${table}.sql`), lines.join('\n'));
}

const md: string[] = [];
md.push('# DKNF Fix — Decision Matrix');
md.push(`Generated: ${new Date().toISOString()}`);
md.push(`Total DKNF-violating columns: **${rows.length}** across ${byTable.size} tables.`);
md.push('');
md.push('| Table | Layer | Column | Proposed ENUM | Values | Decision |');
md.push('|---|---|---|---|---|---|');
for (const r of rows.sort((a, b) => a.table.localeCompare(b.table) || a.column.localeCompare(b.column))) {
  md.push(`| ${r.table} | ${r.layer} | ${r.column} | ${r.enumName} | ${r.values.map((v) => `\`${v}\``).join(', ')} |  |`);
}
writeFileSync(join(OUT_DIR, 'decisions.md'), md.join('\n') + '\n');
console.error(`dknf-fix-plan: ${rows.length} violations across ${byTable.size} tables`);
console.error(`Wrote: ${OUT_DIR}/`);
