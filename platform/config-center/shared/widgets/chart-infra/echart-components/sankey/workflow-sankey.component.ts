/**
 * WorkflowSankeyComponent — Sankey diagram of GRC workflow stage transitions.
 *
 * Uses `buildWorkflowSankeyOptions` from advanced-builders.
 * Requirements: 10.5
 */
import { Component, Input, Output, EventEmitter, ChangeDetectionStrategy, OnInit, OnChanges, SimpleChanges } from '@angular/core';
import { CommonModule } from '@angular/common';
import { AppEchartComponent } from '../../echart-wrapper/app-echart.component';
import { buildWorkflowSankeyOptions } from '../../echart-builders/advanced-builders';
import type { SankeyData } from '../../echart-builders/builder-types';
import type { EChartsOption } from 'echarts';
import { GrcRecord } from '@app/core/models/shared.types';

@Component({
    selector: 'app-workflow-sankey',
    imports: [CommonModule, AppEchartComponent],
    changeDetection: ChangeDetectionStrategy.OnPush,
    template: `
    <app-echart
      [options]="chartOptions"
      [ariaLabel]="'Workflow Sankey Diagram'"
      (chartClick)="onNodeClick($event)">
    </app-echart>
  `,
    styles: [`:host { display: block; width: 100%; height: 100%; }`]
})
export class WorkflowSankeyComponent implements OnInit, OnChanges {
  @Input() data!: SankeyData;
  @Output() nodeDrillDown = new EventEmitter<any>();

  chartOptions: EChartsOption = {};

  ngOnInit(): void {
    this.buildChart();
  }

  ngOnChanges(changes: SimpleChanges): void {
    if (changes['data'] && !changes['data'].firstChange) {
      this.buildChart();
    }
  }

  onNodeClick(event: GrcRecord): void {
    this.nodeDrillDown.emit(event?.data ?? event);
  }

  private buildChart(): void {
    if (this.data) {
      this.chartOptions = buildWorkflowSankeyOptions(this.data);
    }
  }
}
