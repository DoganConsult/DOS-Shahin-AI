import { RedisStreamEventBus } from '@dos/event-backbone';
import { logger } from '@dos/platform-core/observability';
import { ServiceClient } from '@dos/service-client';
import { recordAudit } from '../adapters/audit.adapter';
import { sendNotification } from '../adapters/notification.adapter';
import * as portalService from '../domain/portal.service';
import { publishPortalCreated } from './publisher';

const workflowClient = new ServiceClient({
  baseUrl: process.env.WORKFLOW_SERVICE_URL || 'http://127.0.0.1:4004',
  timeout: 5000,
  retries: 1,
});

export function registerConsumers(eventBus: RedisStreamEventBus): void {
  eventBus.subscribe('vendor.created', async (envelope) => {
    const tenantId = envelope.tenantId;
    const payload = envelope.payload as Record<string, unknown>;
    try {
      logger.info(`[portals-service] Processing vendor.created: Provision vendor portal access for new vendor`, {
        eventId: envelope.eventId,
        tenantId,
      });

      const created = await portalService.create(tenantId, {
          name: (payload.name as string) || `Auto: vendor.created - ${envelope.eventId.slice(0, 8)}`,
          type: (payload.type as string) || (payload.category as string) || 'auto-generated',
          status: 'open',
          description: `Auto-generated from vendor.created event (ID: ${envelope.eventId})`,
        });
        logger.info(`[portals-service] Auto-created portal`, { id: created.portal_id, tenantId });
        await publishPortalCreated(tenantId, created.portal_id, { source: 'vendor.created', autoGenerated: true }, envelope.userId);
        if (envelope.userId) {
          sendNotification(tenantId, envelope.userId, 'Portal Created', `A new portal was auto-created from vendor.created`, 'info', { entityId: created.portal_id }).catch(() => {});
        }

      await recordAudit(
        tenantId,
        'provisionVendorPortalAccess',
        'portal',
        envelope.eventId,
        envelope.userId,
        { source: envelope.source, event: 'vendor.created', payload },
      );
    } catch (err) {
      logger.error(`[portals-service] Failed to process vendor.created`, { eventId: envelope.eventId, error: err });
    }
  });

  eventBus.subscribe('vendor.assessment.completed', async (envelope) => {
    const tenantId = envelope.tenantId;
    const payload = envelope.payload as Record<string, unknown>;
    try {
      logger.info(`[portals-service] Processing vendor.assessment.completed: Update portal assessment status after vendor assessment`, {
        eventId: envelope.eventId,
        tenantId,
      });

      const entityId = (payload.entityId as string) || (payload.portal_id as string);
      if (entityId) {
        const existing = await portalService.getById(tenantId, entityId);
        if (existing) {
          await portalService.update(tenantId, entityId, {
            status: 'under-review',
          });
          logger.info(`[portals-service] updatePortalAssessmentStatus: updated portal`, { entityId, tenantId });
        }
      } else {
        const items = await portalService.list(tenantId, { pageSize: 10, status: 'active' });
        for (const item of items.data) {
          await portalService.update(tenantId, (item as any).portal_id, {
            status: 'under-review',
          });
        }
        logger.info(`[portals-service] updatePortalAssessmentStatus: batch-reviewed portal items`, { count: items.data.length, tenantId });
      }

      await recordAudit(
        tenantId,
        'updatePortalAssessmentStatus',
        'portal',
        envelope.eventId,
        envelope.userId,
        { source: envelope.source, event: 'vendor.assessment.completed', payload },
      );
    } catch (err) {
      logger.error(`[portals-service] Failed to process vendor.assessment.completed`, { eventId: envelope.eventId, error: err });
    }
  });

  eventBus.subscribe('compliance.assessed', async (envelope) => {
    const tenantId = envelope.tenantId;
    const payload = envelope.payload as Record<string, unknown>;
    try {
      logger.info(`[portals-service] Processing compliance.assessed: Update portal compliance status after assessment`, {
        eventId: envelope.eventId,
        tenantId,
      });

      const entityId = (payload.entityId as string) || (payload.portal_id as string);
      if (entityId) {
        const existing = await portalService.getById(tenantId, entityId);
        if (existing) {
          await portalService.update(tenantId, entityId, {
            status: 'under-review',
          });
          logger.info(`[portals-service] updatePortalComplianceStatus: updated portal`, { entityId, tenantId });
        }
      } else {
        const items = await portalService.list(tenantId, { pageSize: 10, status: 'active' });
        for (const item of items.data) {
          await portalService.update(tenantId, (item as any).portal_id, {
            status: 'under-review',
          });
        }
        logger.info(`[portals-service] updatePortalComplianceStatus: batch-reviewed portal items`, { count: items.data.length, tenantId });
      }

      await recordAudit(
        tenantId,
        'updatePortalComplianceStatus',
        'portal',
        envelope.eventId,
        envelope.userId,
        { source: envelope.source, event: 'compliance.assessed', payload },
      );
    } catch (err) {
      logger.error(`[portals-service] Failed to process compliance.assessed`, { eventId: envelope.eventId, error: err });
    }
  });
}
