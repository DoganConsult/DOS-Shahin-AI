import { RedisStreamEventBus } from '@dos/event-backbone';
import { logger } from '@dos/platform-core/observability';
import { ServiceClient } from '@dos/service-client';
import { recordAudit } from '../adapters/audit.adapter';
import { sendNotification } from '../adapters/notification.adapter';
import * as recordService from '../domain/record.service';
import { publishRecordCreated } from './publisher';

const workflowClient = new ServiceClient({
  baseUrl: process.env.WORKFLOW_SERVICE_URL || 'http://127.0.0.1:4004',
  timeout: 5000,
  retries: 1,
});

export function registerConsumers(eventBus: RedisStreamEventBus): void {
  eventBus.subscribe('evidence.submitted', async (envelope) => {
    const tenantId = envelope.tenantId;
    const payload = envelope.payload as Record<string, unknown>;
    try {
      logger.info(`[records-service] Processing evidence.submitted: Auto-create record when evidence submitted`, {
        eventId: envelope.eventId,
        tenantId,
      });

      const created = await recordService.create(tenantId, {
          title: (payload.title as string) || `Auto: evidence.submitted - ${envelope.eventId.slice(0, 8)}`,
          type: (payload.type as string) || (payload.category as string) || 'auto-generated',
          status: 'open',
          description: `Auto-generated from evidence.submitted event (ID: ${envelope.eventId})`,
        });
        logger.info(`[records-service] Auto-created record`, { id: created.record_id, tenantId });
        await publishRecordCreated(tenantId, created.record_id, { source: 'evidence.submitted', autoGenerated: true }, envelope.userId);
        if (envelope.userId) {
          sendNotification(tenantId, envelope.userId, 'Record Created', `A new record was auto-created from evidence.submitted`, 'info', { entityId: created.record_id }).catch(() => {});
        }

      await recordAudit(
        tenantId,
        'createRecordFromEvidence',
        'record',
        envelope.eventId,
        envelope.userId,
        { source: envelope.source, event: 'evidence.submitted', payload },
      );
    } catch (err) {
      logger.error(`[records-service] Failed to process evidence.submitted`, { eventId: envelope.eventId, error: err });
    }
  });

  eventBus.subscribe('policy.published', async (envelope) => {
    const tenantId = envelope.tenantId;
    const payload = envelope.payload as Record<string, unknown>;
    try {
      logger.info(`[records-service] Processing policy.published: Archive previous policy version when new one published`, {
        eventId: envelope.eventId,
        tenantId,
      });

      logger.info(`[records-service] archivePreviousPolicyVersion triggered by policy.published`, { tenantId, payload });

      await recordAudit(
        tenantId,
        'archivePreviousPolicyVersion',
        'record',
        envelope.eventId,
        envelope.userId,
        { source: envelope.source, event: 'policy.published', payload },
      );
    } catch (err) {
      logger.error(`[records-service] Failed to process policy.published`, { eventId: envelope.eventId, error: err });
    }
  });

  eventBus.subscribe('audit.finding.created', async (envelope) => {
    const tenantId = envelope.tenantId;
    const payload = envelope.payload as Record<string, unknown>;
    try {
      logger.info(`[records-service] Processing audit.finding.created: Create compliance record from audit finding`, {
        eventId: envelope.eventId,
        tenantId,
      });

      const created = await recordService.create(tenantId, {
          title: (payload.title as string) || `Auto: audit.finding.created - ${envelope.eventId.slice(0, 8)}`,
          type: (payload.type as string) || (payload.category as string) || 'auto-generated',
          status: 'open',
          description: `Auto-generated from audit.finding.created event (ID: ${envelope.eventId})`,
        });
        logger.info(`[records-service] Auto-created record`, { id: created.record_id, tenantId });
        await publishRecordCreated(tenantId, created.record_id, { source: 'audit.finding.created', autoGenerated: true }, envelope.userId);
        if (envelope.userId) {
          sendNotification(tenantId, envelope.userId, 'Record Created', `A new record was auto-created from audit.finding.created`, 'info', { entityId: created.record_id }).catch(() => {});
        }

      await recordAudit(
        tenantId,
        'createRecordFromFinding',
        'record',
        envelope.eventId,
        envelope.userId,
        { source: envelope.source, event: 'audit.finding.created', payload },
      );
    } catch (err) {
      logger.error(`[records-service] Failed to process audit.finding.created`, { eventId: envelope.eventId, error: err });
    }
  });
}
