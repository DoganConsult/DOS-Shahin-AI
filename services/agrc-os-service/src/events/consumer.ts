import { RedisStreamEventBus } from '@dos/event-backbone';
import { logger } from '@dos/platform-core/observability';
import { ServiceClient } from '@dos/service-client';
import { recordAudit } from '../adapters/audit.adapter';
import { sendNotification } from '../adapters/notification.adapter';
import * as agrcTaskService from '../domain/agrc-task.service';
import { publishAgrcTaskCreated } from './publisher';

const workflowClient = new ServiceClient({
  baseUrl: process.env.WORKFLOW_SERVICE_URL || 'http://127.0.0.1:4004',
  timeout: 5000,
  retries: 1,
});

export function registerConsumers(eventBus: RedisStreamEventBus): void {
  eventBus.subscribe('workflow.task.assigned', async (envelope) => {
    const tenantId = envelope.tenantId;
    const payload = envelope.payload as Record<string, unknown>;
    try {
      logger.info(`[agrc-os-service] Processing workflow.task.assigned: Create AI GRC task from workflow task assignment`, {
        eventId: envelope.eventId,
        tenantId,
      });

      const created = await agrcTaskService.create(tenantId, {
          title: (payload.title as string) || `Auto: workflow.task.assigned - ${envelope.eventId.slice(0, 8)}`,
          type: (payload.type as string) || (payload.category as string) || 'auto-generated',
          status: 'open',
          description: `Auto-generated from workflow.task.assigned event (ID: ${envelope.eventId})`,
        });
        logger.info(`[agrc-os-service] Auto-created agrc-task`, { id: created.task_id, tenantId });
        await publishAgrcTaskCreated(tenantId, created.task_id, { source: 'workflow.task.assigned', autoGenerated: true }, envelope.userId);
        if (envelope.userId) {
          sendNotification(tenantId, envelope.userId, 'AgrcTask Created', `A new agrc-task was auto-created from workflow.task.assigned`, 'info', { entityId: created.task_id }).catch(() => {});
        }

      await recordAudit(
        tenantId,
        'createAgrcFromWorkflow',
        'agrc-task',
        envelope.eventId,
        envelope.userId,
        { source: envelope.source, event: 'workflow.task.assigned', payload },
      );
    } catch (err) {
      logger.error(`[agrc-os-service] Failed to process workflow.task.assigned`, { eventId: envelope.eventId, error: err });
    }
  });

  eventBus.subscribe('incident.created', async (envelope) => {
    const tenantId = envelope.tenantId;
    const payload = envelope.payload as Record<string, unknown>;
    try {
      logger.info(`[agrc-os-service] Processing incident.created: Create AI investigation task for incident`, {
        eventId: envelope.eventId,
        tenantId,
      });

      const created = await agrcTaskService.create(tenantId, {
          title: (payload.title as string) || `Auto: incident.created - ${envelope.eventId.slice(0, 8)}`,
          type: (payload.type as string) || (payload.category as string) || 'auto-generated',
          status: 'open',
          description: `Auto-generated from incident.created event (ID: ${envelope.eventId})`,
        });
        logger.info(`[agrc-os-service] Auto-created agrc-task`, { id: created.task_id, tenantId });
        await publishAgrcTaskCreated(tenantId, created.task_id, { source: 'incident.created', autoGenerated: true }, envelope.userId);
        if (envelope.userId) {
          sendNotification(tenantId, envelope.userId, 'AgrcTask Created', `A new agrc-task was auto-created from incident.created`, 'info', { entityId: created.task_id }).catch(() => {});
        }

      await recordAudit(
        tenantId,
        'createInvestigationTask',
        'agrc-task',
        envelope.eventId,
        envelope.userId,
        { source: envelope.source, event: 'incident.created', payload },
      );
    } catch (err) {
      logger.error(`[agrc-os-service] Failed to process incident.created`, { eventId: envelope.eventId, error: err });
    }
  });

  eventBus.subscribe('compliance.gap.identified', async (envelope) => {
    const tenantId = envelope.tenantId;
    const payload = envelope.payload as Record<string, unknown>;
    try {
      logger.info(`[agrc-os-service] Processing compliance.gap.identified: Create AI compliance remediation task`, {
        eventId: envelope.eventId,
        tenantId,
      });

      const created = await agrcTaskService.create(tenantId, {
          title: (payload.title as string) || `Auto: compliance.gap.identified - ${envelope.eventId.slice(0, 8)}`,
          type: (payload.type as string) || (payload.category as string) || 'auto-generated',
          status: 'open',
          description: `Auto-generated from compliance.gap.identified event (ID: ${envelope.eventId})`,
        });
        logger.info(`[agrc-os-service] Auto-created agrc-task`, { id: created.task_id, tenantId });
        await publishAgrcTaskCreated(tenantId, created.task_id, { source: 'compliance.gap.identified', autoGenerated: true }, envelope.userId);
        if (envelope.userId) {
          sendNotification(tenantId, envelope.userId, 'AgrcTask Created', `A new agrc-task was auto-created from compliance.gap.identified`, 'info', { entityId: created.task_id }).catch(() => {});
        }

      await recordAudit(
        tenantId,
        'createComplianceTask',
        'agrc-task',
        envelope.eventId,
        envelope.userId,
        { source: envelope.source, event: 'compliance.gap.identified', payload },
      );
    } catch (err) {
      logger.error(`[agrc-os-service] Failed to process compliance.gap.identified`, { eventId: envelope.eventId, error: err });
    }
  });
}
